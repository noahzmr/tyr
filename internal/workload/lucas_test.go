// exactLL is the reference: s → s² − 2 mod 2^p − 1 with math/big.
func exactLL(p, iters uint) uint64 {
	m := new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), p), big.NewInt(1))
	s, two := big.NewInt(4), big.NewInt(2)
	for i := uint(0); i < iters; i++ {
		s.Mul(s, s)
		s.Sub(s, two)
		s.Mod(s, m)
	}
	return s.Uint64() // low 64 bits (s ≥ 0)
}

func TestLLMatchesExact(t *testing.T) {
	for _, c := range []struct{ p, iters uint }{{11, 5}, {61, 40}, {127, 100}, {4253, 300}, {9941, 200}, {21701, 50}, {1257787, 2}} {
		s := newLL(c.p)
		s.set(4)
		worst := 0.0
		for i := uint(0); i < c.iters; i++ {
			worst = max(worst, s.step())
		}
		if got, want := s.residue(), exactLL(c.p, c.iters); got != want {
			t.Errorf("M%d after %d: %#x, want %#x", c.p, c.iters, got, want)
		}
		if worst > 0.1 {
			t.Errorf("M%d: round-off %.3f too close to the limit (FFT %d)", c.p, worst, LLCase{P: c.p}.FFTSize())
		}
	}
}

// Mersenne primes end at 0, a composite does not.
func TestLLPrimes(t *testing.T) {
	for _, p := range []uint{127, 521, 607, 4253} {
		if err := RunLL(LLCase{P: p, Iters: p - 2}, nil); err != nil {
			t.Errorf("M%d: %v", p, err)
		}
	}
	err := RunLL(LLCase{P: 4271, Iters: 4269}, nil) // 2^4271 − 1 is composite
	var le *LLError
	if !errors.As(err, &le) || le.Got == 0 {
		t.Errorf("composite M4271 passed: %v", err)
	}
}

// One flipped bit in the middle of a run (a core computing wrong) is caught.
func TestLLDetectsCorruption(t *testing.T) {
	c := LLCase{P: 4423, Iters: 4421}
	s := newL(c)
	for i := uint(1); i <= c.Iters; i++ {
		s.step()
		if i == 2000 {
			s.digit[37] ^= 1 << 3
		}
	}
	if s.residue() == 0 {
		t.Fatal("corrupted run still ended at 0")
	}
}

func newL(c LLCase) *llState {
	s := newLL(c.P)
	s.set(4)
	return s
}

func TestTortureCases(t *testing.T) {
	for _, m := range []string{"small", "large", "blend"} {
		cs := TortureCases(m)
		if len(cs) == 0 {
			t.Fatalf("%s: no cases", m)
		}
		for _, c := range cs {
			if c.Iters < c.P-2 && llResidues[c.P] == 0 {
				t.Errorf("M%d: no residue in the table (go test ./internal/workload -run TestLLTable -update)", c.P)
			}
		}
	}
	if s, l := TortureCases("small")[0].FFTSize(), TortureCases("large")[0].FFTSize(); s > 4096 || l < 1<<17 {
		t.Errorf("FFT sizes small %d large %d", s, l)
	}
}

// TestLLTable writes ll_table.go with -update: the residues of the large
// cases, computed exactly (slow: about a minute).
func TestLLTable(t *testing.T) {
	if !*update {
		for _, c := range largeFFT {
			if _, ok := llResidues[c.P]; !ok {
				t.Errorf("M%d missing from ll_table.go", c.P)
			}
		}
		return
	}
	var b strings.Builder
	b.WriteString("// Code generated by `go test ./internal/workload -run TestLLTable -update`. DO NOT EDIT.\n\npackage workload\n\n// llResidues: the low 64 bits of the Lucas-Lehmer residue after the\n// iterations of each large case, computed with exact integer arithmetic.\nvar llResidues = map[uint]uint64{\n")
	cs := append([]LLCase(nil), largeFFT...)
	sort.Slice(cs, func(i, j int) bool { return cs[i].P < cs[j].P })
	for _, c := range cs {
		fmt.Fprintf(&b, "\t%d: %#016x, // %d iterations\n", c.P, exactLL(c.P, c.Iters), c.Iters)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("ll_table.go", []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
}
